package com.example.planner.user;

/**
 * Состояние аккаунта. Значения совпадают с {@code users_status_check} в БД:
 * добавляя сюда новое, нужна и миграция, расширяющая CHECK.
 */
public enum UserStatus {
    /** Зарегистрировался сам, ещё не подтвердил почту. */
    PENDING_VERIFICATION,
    /** Приглашён администратором, ещё не установил пароль. */
    INVITED,
    /** Может входить. */
    ACTIVE,
    /** Временно заблокирован (например, после серии неудачных входов). */
    LOCKED,
    /** Заблокирован администратором. */
    BLOCKED,
    /** Удалён (строка остаётся для истории). */
    DELETED
}
