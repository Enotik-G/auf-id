package ru.auf.id.admin;

/**
 * Вид клиента. Определяет сразу всё: как он доказывает, что это он, какие потоки ему разрешены,
 * нужны ли адреса возврата и выдаётся ли refresh-токен.
 *
 * <p>Понятие введено нарочно, вместо того чтобы давать администратору собирать настройки по частям.
 * Самый частый способ сломать OAuth — несочетаемый набор: публичный клиент с секретом (секрет в
 * браузере не спрятать, и он создаёт ложное чувство защиты), сервисный клиент с адресом возврата
 * (возвращаться некуда, человека в потоке нет) или клиент с кодом авторизации без PKCE.
 */
public enum ClientKind {

    /**
     * Настольное или мобильное приложение: лаунчер, игра, мобильный клиент. Возврат — на
     * {@code http://127.0.0.1:<порт>}, который приложение занимает на время входа.
     *
     * <p><b>Единственный вид, которому выдаётся refresh-токен</b> (решение 2026-10-08): такое
     * приложение запускают часто и надолго, а refresh-токен ему есть куда положить — в хранилище
     * секретов операционной системы (Credential Manager, Keychain, Secret Service).
     *
     * <p><b>Секрет клиента ему выдаётся, хотя спрятать его в программе на чужом компьютере
     * невозможно</b> (решение 2026-10-08). Это выглядит противоречием, поэтому стоит объяснить:
     * <ul>
     *   <li>настоящую защиту в этом потоке даёт <b>PKCE</b>, а не секрет: перехваченный код
     *       бесполезен без {@code code_verifier}, который не покидает приложение. Секрет не
     *       добавляет защиты и не убавляет её — он просто есть;</li>
     *   <li>без него Spring Authorization Server отказывается обменивать refresh-токен:
     *       {@code PublicClientAuthenticationConverter} опознаёт клиента <b>только</b> по запросу
     *       с PKCE, а в запросе на обновление PKCE нет. Обойти это можно было бы своим
     *       {@code AuthenticationConverter} в пути аутентификации — но свой код в аутентификации
     *       опаснее фиктивного секрета;</li>
     *   <li>так устроен и поток Google для настольных приложений: секрет там выдаётся и в
     *       документации прямо сказано, что секретом его считать не следует.</li>
     * </ul>
     * Поэтому секрет здесь — пропуск к ручке обновления, а не доказательство подлинности. Красть
     * его бессмысленно: он не даёт доступа ни к одной учётной записи, человек всё равно должен
     * войти сам.
     */
    NATIVE,

    /**
     * Приложение, живущее в браузерной вкладке (SPA). Публичный клиент: без секрета, с PKCE.
     *
     * <p><b>Refresh-токен ему не выдаётся</b>: в браузере его негде спрятать от XSS, а живёт он
     * 30 дней. Вкладка продлевает вход иначе — молча идёт на {@code /oauth2/authorize}, где её
     * узнаёт сессия провайдера.
     */
    BROWSER,

    /**
     * Серверное приложение: секрет хранится на сервере, PKCE всё равно обязателен (OAuth 2.1).
     * Нужны адреса возврата. Refresh-токен не выдаётся, пока в этом не появится нужды: серверное
     * приложение держит свою сессию с человеком само.
     */
    CONFIDENTIAL,

    /**
     * Сервис, который ходит к другим сервисам от своего имени, без человека: поток
     * {@code client_credentials}. Адресов возврата быть не должно — возвращаться некуда.
     * Refresh-токен здесь бессмыслен: за новым access-токеном сервис приходит со своим секретом.
     */
    SERVICE;

    /**
     * Обходится ли клиент вовсе без секрета.
     *
     * <p>Только {@link #BROWSER}. У {@link #NATIVE} секрет есть, хотя и не настоящий — см. его
     * описание: без секрета Spring не даёт обменять refresh-токен.
     */
    boolean isPublic() {
        return this == BROWSER;
    }

    /** Выдаётся ли клиенту refresh-токен. */
    boolean issuesRefreshTokens() {
        return this == NATIVE;
    }
}
