package ru.auf.id.admin;

/**
 * Операция оставила бы систему без ни одного работоспособного администратора.
 *
 * <p>Защита от самой дорогой ошибки в админке: снять роль себе или заблокировать себя, оставшись
 * единственным администратором. Восстановить доступ после этого можно только правкой базы руками —
 * механизм {@code auth.bootstrap.admin-emails} спасёт лишь если он настроен заранее.
 */
public class LastAdminException extends RuntimeException {

    public LastAdminException(String operation) {
        super(operation + ": в системе не останется ни одного действующего администратора");
    }
}
