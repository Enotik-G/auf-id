package ru.auf.id.user;

/**
 * Состояние аккаунта. Значения совпадают с {@code users_status_check} в БД:
 * добавляя сюда новое, нужна и миграция, расширяющая CHECK.
 */
public enum UserStatus {
    /** Приглашён администратором, ещё не установил пароль. */
    INVITED,
    /** Может входить. */
    ACTIVE,
    /**
     * Вход закрыт — задел на будущее, сейчас в этот статус не переводит ничто.
     *
     * <p>Изначально так закрывали аккаунт за неудачные входы, но это отменило решение 4.4.5 (вместо
     * блокировки — капча): иначе чужой аккаунт можно было бы держать закрытым. Значение оставлено
     * (решение 2026-10-10), чтобы админка могла отличать «закрыли за поведение» от {@code BLOCKED}.
     */
    LOCKED,
    /** Заблокирован администратором. */
    BLOCKED,
    /** Удалён (строка остаётся для истории). */
    DELETED
}
