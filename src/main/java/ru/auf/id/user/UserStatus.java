package ru.auf.id.user;

/**
 * Состояние аккаунта. Значения совпадают с {@code users_status_check} в БД:
 * добавляя сюда новое, нужна и миграция, расширяющая CHECK.
 */
public enum UserStatus {
    /** Приглашён администратором, ещё не установил пароль. */
    INVITED,
    /** Может входить. */
    ACTIVE,
    /**
     * Вход закрыт, но не администратором.
     *
     * <p>Сейчас в этот статус не переводит ничто: блокировку аккаунта за неудачные входы отменило
     * решение 4.4.5 (вместо неё капча), иначе чужой аккаунт можно было бы держать закрытым.
     * Значение оставлено для админки — отличать «закрыли за поведение» от `BLOCKED`.
     */
    LOCKED,
    /** Заблокирован администратором. */
    BLOCKED,
    /** Удалён (строка остаётся для истории). */
    DELETED
}
