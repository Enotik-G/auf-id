package ru.auf.id.user;

/**
 * Роль пользователя в экосистеме колледжа.
 *
 * <p>Роли намеренно крупные, и их три. Такая роль — это общий словарь доступа: она едет в токене, и
 * каждый сервис экосистемы решает по ней, пускать ли вообще. Всё, что тоньше — «этот куратор правит
 * только свою группу», «этот студент видит только свои заметки» — решает тот сервис, которому эти
 * данные принадлежат, потому что только у него они есть. В токен такие правила не кладём: он
 * раздувается и устаревает между выдачами.
 *
 * <p>Значения дублируются в ограничении {@code user_roles_role_check} миграции 006. Добавление новой
 * роли — это новый changeset, переопределяющий {@code CHECK}, а не правка старого.
 */
public enum Role {

    /** Полный доступ к админке: создаёт учётки, банит, выдаёт роли, регистрирует клиентов. */
    ADMIN,

    /** Ведёт свои группы: смотрит состав и статистику. Сами группы живут в профильном сервисе. */
    CURATOR,

    /** Обычный пользователь сервисов колледжа. */
    STUDENT
}
